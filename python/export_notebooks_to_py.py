#!/usr/bin/env python3
"""export_notebooks_to_py.py — mirror every .ipynb in this folder tree to a .py.

Writes a percent-format script (``# %%`` cell markers, markdown cells as comments)
next to each notebook, so you always have a plain-Python, diff-friendly copy.
The notebook stays the source of truth; re-run this after editing notebooks.

    python export_notebooks_to_py.py            # convert all notebooks under ./
    python export_notebooks_to_py.py --check     # list what WOULD change, write nothing
"""
import argparse
import json
import os
import sys

SKIP_DIRS = {".ipynb_checkpoints", "__pycache__", ".git"}


def notebook_to_py(path):
    nb = json.load(open(path, encoding="utf-8"))
    stem = os.path.basename(path)[:-6]  # strip .ipynb
    lines = [f"# Auto-generated from {stem}.ipynb by export_notebooks_to_py.py.",
             "# Edit the notebook, then re-run the exporter; do not edit this file by hand.",
             ""]
    for cell in nb.get("cells", []):
        src = "".join(cell.get("source", []))
        if cell["cell_type"] == "code":
            lines.append("# %%")
            lines.append(src.rstrip("\n"))
            lines.append("")
        elif cell["cell_type"] == "markdown":
            lines.append("# %% [markdown]")
            for ln in src.split("\n"):
                lines.append(("# " + ln).rstrip())
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"

ap = argparse.ArgumentParser()
ap.add_argument("--root", default=".", help="folder to scan (default: current)")
ap.add_argument("--check", action="store_true", help="report only, write nothing")
ap.add_argument("--force", action="store_true",
                help="also overwrite hand-written .py files (default: protect them)")
args = ap.parse_args()

MARKER = "by export_notebooks_to_py.py"

n = 0
for dirpath, dirnames, filenames in os.walk(args.root):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    for fn in filenames:
        if not fn.endswith(".ipynb"):
            continue
        ipath = os.path.join(dirpath, fn)
        opath = ipath[:-6] + ".py"
        new = notebook_to_py(ipath)
        old = open(opath, encoding="utf-8").read() if os.path.exists(opath) else None
        rel = os.path.relpath(opath, args.root)
        # protect hand-written scripts: only manage .py we generated
        if old is not None and MARKER not in old.splitlines()[0:2].__str__() and not args.force:
            print("skip(hand-written) " + rel)
            n += 1
            continue
        changed = new != old
        if args.check:
            print(("WOULD UPDATE " if changed else "unchanged   ") + rel)
        else:
            if changed:
                open(opath, "w", encoding="utf-8").write(new)
            print(("wrote  " if changed else "same   ") + rel)
        n += 1
print(f"\n{n} notebook(s) processed.")
